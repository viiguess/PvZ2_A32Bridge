#!/usr/bin/env python3
"""Assembles tools/softfloat_vfp.S and writes src/runtime/softfloat_vfp.h (the code, and the offset of the VFP
version of each libgcc helper).

    python tools/gen_softfloat_vfp.py [llvm-bin-dir]      (default: the NDK in $ANDROID_NDK / $ANDROID_NDK_HOME)
"""
import glob
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = '.exe' if os.name == 'nt' else ''
if len(sys.argv) > 1:
    BIN = sys.argv[1]
else:
    ndk = os.environ.get('ANDROID_NDK') or os.environ.get('ANDROID_NDK_HOME')
    if not ndk:
        sys.exit('set ANDROID_NDK or pass the llvm bin directory of an NDK')
    BIN = glob.glob(os.path.join(ndk, 'toolchains', 'llvm', 'prebuilt', '*', 'bin'))[0]

# libgcc / RTABI names -> replacement label (aliases share an address in the game library)
NAMES = {
    'fadd': ['__aeabi_fadd', '__addsf3'], 'fsub': ['__aeabi_fsub', '__subsf3'], 'frsub': ['__aeabi_frsub'],
    'fmul': ['__aeabi_fmul', '__mulsf3'], 'fdiv': ['__aeabi_fdiv', '__divsf3'],
    'dadd': ['__aeabi_dadd', '__adddf3'], 'dsub': ['__aeabi_dsub', '__subdf3'], 'drsub': ['__aeabi_drsub'],
    'dmul': ['__aeabi_dmul', '__muldf3'], 'ddiv': ['__aeabi_ddiv', '__divdf3'],
    'f2d': ['__aeabi_f2d', '__extendsfdf2'], 'd2f': ['__aeabi_d2f', '__truncdfsf2'],
    'i2f': ['__aeabi_i2f', '__floatsisf'], 'ui2f': ['__aeabi_ui2f', '__floatunsisf'],
    'i2d': ['__aeabi_i2d', '__floatsidf'], 'ui2d': ['__aeabi_ui2d', '__floatunsidf'],
    'f2iz': ['__aeabi_f2iz', '__fixsfsi'], 'f2uiz': ['__aeabi_f2uiz', '__fixunssfsi'],
    'd2iz': ['__aeabi_d2iz', '__fixdfsi'], 'd2uiz': ['__aeabi_d2uiz', '__fixunsdfsi'],
    'cfcmple': ['__aeabi_cfcmple', '__aeabi_cfcmpeq'], 'cfrcmple': ['__aeabi_cfrcmple'],
    'cdcmple': ['__aeabi_cdcmple', '__aeabi_cdcmpeq'], 'cdrcmple': ['__aeabi_cdrcmple'],
    'gesf2': ['__gesf2', '__gtsf2'], 'lesf2': ['__lesf2', '__ltsf2', '__eqsf2', '__nesf2'],
    'gedf2': ['__gedf2', '__gtdf2'], 'ledf2': ['__ledf2', '__ltdf2', '__eqdf2', '__nedf2'],
}
for kind in ('f', 'd'):
    for rel in ('eq', 'lt', 'le', 'ge', 'gt', 'un'):
        NAMES['%scmp%s' % (kind, rel)] = ['__aeabi_%scmp%s' % (kind, rel)]

with tempfile.TemporaryDirectory() as tmp:
    obj, raw = os.path.join(tmp, 'v.o'), os.path.join(tmp, 'v.bin')
    subprocess.check_call([os.path.join(BIN, 'clang' + EXE), '--target=armv7a-linux-androideabi', '-c',
                           os.path.join(ROOT, 'tools', 'softfloat_vfp.S'), '-o', obj])
    subprocess.check_call([os.path.join(BIN, 'llvm-objcopy' + EXE), '-O', 'binary', '--only-section=.text', obj, raw])
    code = open(raw, 'rb').read()
    nm = subprocess.check_output([os.path.join(BIN, 'llvm-nm' + EXE), obj], text=True)
offsets = {m.group(2): int(m.group(1), 16) for m in re.finditer(r'^([0-9a-f]+) T vfp_(\w+)$', nm, re.M)}
missing = sorted(set(NAMES) - set(offsets))
if missing:
    sys.exit('labels missing from softfloat_vfp.S: %s' % missing)

words = [int.from_bytes(code[i:i + 4], 'little') for i in range(0, len(code), 4)]
out = ['// Generated by tools/gen_softfloat_vfp.py from tools/softfloat_vfp.S. Do not edit.', '#pragma once', '',
       '#include "common.h"', '',
       'static const u32 kSoftFloatVfpCode[] = {']
for i in range(0, len(words), 6):
    out.append('    ' + ' '.join('0x%08x,' % w for w in words[i:i + 6]))
out += ['};', '',
        'struct SoftFloatVfpEntry {', '  const char* name;', '  u32 offset;  // bytes into kSoftFloatVfpCode', '};', '',
        'static const SoftFloatVfpEntry kSoftFloatVfpEntries[] = {']
for label in sorted(NAMES):
    for name in NAMES[label]:
        out.append('    {"%s", 0x%x},' % (name, offsets[label]))
out += ['};', '']
path = os.path.join(ROOT, 'src', 'runtime', 'softfloat_vfp.h')
open(path, 'w', newline='\n').write('\n'.join(out))
print('%s: %d bytes of code, %d entry names' % (path, len(code), sum(map(len, NAMES.values()))))
